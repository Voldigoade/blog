export const dictionaries: Record<LocaleRoute, Dictionary> = {
  fr,
  en,
  es,
  de,
};

export function getDict(route: string): Dictionary {
  return dictionaries[route as LocaleRoute] ?? fr;
}

export function sectionText(route: string, id: string): { name: string; title: string; description: string } {
  const d = getDict(route);
  if (id === "science") return { name: d.sectionScienceName, title: d.sectionScienceTitle, description: d.sectionScienceDesc };
  if (id === "computing") return { name: d.sectionComputingName, title: d.sectionComputingTitle, description: d.sectionComputingDesc };
  return { name: d.sectionAnimeName, title: d.sectionAnimeTitle, description: d.sectionAnimeDesc };
}

export function sectionPubsText(route: string, sectionTitle: string): string {
  return getDict(route).pubsInSection.replace("{s}", sectionTitle);
}

export function countText(route: string, n: number): string {
  const d = getDict(route);
  return `${n} ${n > 1 ? d.pubMany : d.pubOne}`;
}

export function readingText(route: string, minutes: number): string {
  const d = getDict(route);
  if (minutes <= 1) return d.readingOne;
  return `${minutes} ${d.readingMany}`;
}
